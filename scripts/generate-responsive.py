"""Regenerate the bundled desktop-first utilities; Python is only for maintainers.
Applications only load ui.css. Existing md/lg utilities keep their behavior.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / 'assets/css'
SOURCES = ['components/flex.css', 'components/typography.css', 'spacing-utilities.css']
helpers = {
    '.ui-hidden': 'display:none !important;',
    '.ui-block:where(:not([hidden]))': 'display:block !important;',
    '.ui-inline:where(:not([hidden]))': 'display:inline !important;',
    '.ui-flex:where(:not([hidden]))': 'display:flex !important;',
    '.ui-inline-flex:where(:not([hidden]))': 'display:inline-flex !important;',
    '.ui-grid:where(:not([hidden]))': 'display:grid !important;',
    '.ui-w-full': 'width:100%; max-width:100%; min-width:0;',
    '.ui-w-auto': 'width:auto;',
    '.ui-overflow-x-auto': 'max-width:100%; overflow-x:auto;',
}
rules = dict(helpers)
for source in SOURCES:
    text = re.sub(r'/\*.*?\*/', '', (CSS / source).read_text(), flags=re.S)
    for match in re.finditer(r'([^{}]+)\{([^{}]*)\}', text):
        # Only collect top-level declarations, not existing responsive overrides.
        before = text[:match.start()]
        if before.count('{') != before.count('}'):
            continue
        for selector in match[1].strip().split(','):
            selector = selector.strip()
            if not re.match(r'\.(?:fx|sp|type)[-\s.>:]', selector + ' '):
                continue
            if 'type-sample' in selector or selector == '.fx-responsive':
                continue
            rules.setdefault(selector, match[2].strip())

def variant(selector, device):
    # Child widths and flex-gap variables must retain the .fx-grid parent.
    classes = re.findall(r'\.([a-z][a-z0-9-]*)', selector)
    target = classes[-1]
    return selector.replace('.' + target, '.' + device + r'\:' + target, 1)

output = ['/* Generated by scripts/generate-responsive.py. No runtime build required.',
          '   PC: base classes; tablet: 768–1023px; mobile: below 768px.',
          '   Device prefixes are independent ranges; hidden attributes stay hidden. */']
output += [f'{selector} {{ {body} }}' for selector, body in helpers.items()]
for device, query in [('tablet', '(768px <= width < 1024px)'), ('mobile', '(width < 768px)')]:
    output.append('@media ' + query + ' {')
    output += [f'  {variant(selector, device)} {{ {body} }}' for selector, body in rules.items()]
    output.append('}')
(CSS / 'responsive-utilities.css').write_text('\n'.join(output) + '\n')
print(f'Generated {len(rules)} rules per device in responsive-utilities.css')
