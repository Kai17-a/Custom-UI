#!/usr/bin/env python3
"""Generate static palette CSS from recorded official-HCT results; no packages/network.
Run: python3 scripts/generate-color-palettes.py
The source revision, HCT inputs and per-role tones are recorded in color-palettes.json.
Applications load the generated CSS through ui.css; no generator runs in the browser.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'scripts/color-palettes.json').read_text())

def token(role):
    # Success/warning/info extend Material's semantic roles; they keep fixed hues.
    return ('--ui-color-' if role.removeprefix('on-').split('-')[0] in ('success', 'warning', 'info') else '--md-sys-color-') + role

def rgb(color):
    return ', '.join(str(int(color[index:index+2], 16)) for index in (1, 3, 5))

def luminance(color):
    channels = [int(color[index:index+2], 16) / 255 for index in (1, 3, 5)]
    channels = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(a * b for a, b in zip(channels, (.2126, .7152, .0722)))

def contrast(a, b):
    low, high = sorted((luminance(a), luminance(b)))
    return (high + .05) / (low + .05)

lines = ['/* Generated by scripts/generate-color-palettes.py; do not edit color values here.',
         '   Material Color Utilities HCT revision: ' + data['revision'],
         '   Custom low-chroma palettes; Material 3 standard light/dark color roles.',
         '   Source, HCT inputs and tones: scripts/color-palettes.json. */']
minimum = 21
for palette in data['palettes']:
    name = palette['name']
    for mode, entry in palette['modes'].items():
        roles = entry['roles']
        for role in ('primary', 'secondary', 'tertiary', 'error', 'success', 'warning', 'info'):
            for foreground, background in [('on-' + role, role), ('on-' + role + '-container', role + '-container')]:
                ratio = contrast(roles[foreground], roles[background]); minimum = min(minimum, ratio)
                assert ratio >= 4.5, (name, mode, foreground, background, ratio)
        for foreground, background in [('on-surface', 'surface'), ('on-surface-variant', 'surface-container-highest'), ('primary', 'surface')]:
            ratio = contrast(roles[foreground], roles[background]); minimum = min(minimum, ratio)
            assert ratio >= 4.5, (name, mode, foreground, background, ratio)
        selector = f':root[data-ui-palette="{name}"]' if mode == 'light' else f':root[data-bs-theme="dark"][data-ui-palette="{name}"]'
        lines.extend(['', selector + ' {'])
        lines.extend(f'  {token(role)}: {value};' for role, value in roles.items())
        mapping = {'--bs-body-bg':'surface', '--bs-body-color':'on-surface', '--bs-secondary-color':'on-surface-variant', '--bs-secondary-bg':'surface-container-high', '--bs-tertiary-bg':'surface-container-low', '--bs-border-color':'outline-variant', '--ui-control-outline':'outline'}
        for name_role, material_role in mapping.items(): lines.append(f'  {name_role}: var({token(material_role)});')
        for ui, material in [('primary', 'primary'), ('danger', 'error'), ('success', 'success'), ('warning', 'warning'), ('info', 'info')]:
            for suffix, role in [('', material), ('-bg-subtle', material+'-container'), ('-border-subtle', material+'-container'), ('-text-emphasis', 'on-'+material+'-container')]:
                lines.append(f'  --bs-{ui}{suffix}: var({token(role)});')
            lines.append(f'  --ui-on-{ui}: var({token("on-"+material)});')
        lines.append(f'  --bs-primary-rgb: {rgb(roles["primary"])};')
        # Encoded SVG strokes must follow the same on-primary role as radio dots.
        ink=roles['on-primary'].replace('#','%23')
        lines.append('  --ui-palette-check-tick: url("data:image/svg+xml,%3csvg xmlns=\'http://www.w3.org/2000/svg\' viewBox=\'0 0 20 20\'%3e%3cpath fill=\'none\' stroke=\''+ink+'\' stroke-linecap=\'round\' stroke-linejoin=\'round\' stroke-width=\'2.6\' d=\'m4 10 4 4 8-8\'/%3e%3c/svg%3e");')
        lines.append('  --ui-palette-check-dash: url("data:image/svg+xml,%3csvg xmlns=\'http://www.w3.org/2000/svg\' viewBox=\'0 0 20 20\'%3e%3cpath stroke=\''+ink+'\' stroke-width=\'2.6\' stroke-linecap=\'round\' d=\'M5 10h10\'/%3e%3c/svg%3e");')
        lines.append('}')
    lines.extend(['', f'.ui-palette-swatch[data-ui-palette-swatch="{name}"] {{ background:{palette["modes"]["light"]["roles"]["primary"]}; }}', f'[data-bs-theme="dark"] .ui-palette-swatch[data-ui-palette-swatch="{name}"] {{ background:{palette["modes"]["dark"]["roles"]["primary"]}; }}'])
(ROOT / 'assets/css/color-palettes.css').write_text('\n'.join(lines) + '\n')
print(f'Generated {len(data["palettes"])} palettes × light/dark; minimum checked text contrast {minimum:.2f}:1')
